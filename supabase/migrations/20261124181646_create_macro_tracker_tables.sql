  public.macro_meal_entries_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.macro_record_login_failure(p_username text, p_client_key text)
RETURNS TABLE (failed_attempts integer, locked_until timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_attempts integer;
  v_locked_until timestamptz;
BEGIN
  INSERT INTO public.macro_login_attempts AS attempts
    (username, client_key, window_started_at, failed_attempts, locked_until)
  VALUES (lower(trim(p_username)), p_client_key, now(), 1, NULL)
  ON CONFLICT (username, client_key) DO UPDATE SET
    window_started_at = CASE
      WHEN attempts.window_started_at <= now() - interval '15 minutes' THEN now()
      ELSE attempts.window_started_at
    END,
    failed_attempts = CASE
      WHEN attempts.window_started_at <= now() - interval '15 minutes' THEN 1
      ELSE attempts.failed_attempts + 1
    END,
    locked_until = CASE
      WHEN (CASE
        WHEN attempts.window_started_at <= now() - interval '15 minutes' THEN 1
        ELSE attempts.failed_attempts + 1
      END) >= 8 THEN now() + interval '15 minutes'
      ELSE NULL
    END
  RETURNING attempts.failed_attempts, attempts.locked_until INTO v_attempts, v_locked_until;

  RETURN QUERY SELECT v_attempts, v_locked_until;
END;
$$;

CREATE OR REPLACE FUNCTION public.macro_clear_login_failures(p_username text, p_client_key text)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  DELETE FROM public.macro_login_attempts
  WHERE username = lower(trim(p_username)) AND client_key = p_client_key;
$$;

REVOKE ALL ON FUNCTION public.macro_record_login_failure(text, text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.macro_clear_login_failures(text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.macro_record_login_failure(text, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.macro_clear_login_failures(text, text) TO service_role;
