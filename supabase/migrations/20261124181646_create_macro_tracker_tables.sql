-- App-owned Supabase schema. All names are prefixed with macro_.
-- RLS and client-role ACLs intentionally prevent direct table access; only
-- the server-side macro-api Edge Function uses the service-role credential.

CREATE TABLE IF NOT EXISTS public.macro_users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username text NOT NULL UNIQUE,
  pin_salt text NOT NULL,
  pin_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.macro_user_foods (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.macro_users(id) ON DELETE CASCADE,
  name text NOT NULL,
  calories double precision NOT NULL DEFAULT 0 CHECK (calories >= 0),
  protein double precision NOT NULL DEFAULT 0 CHECK (protein >= 0),
  carbs double precision NOT NULL DEFAULT 0 CHECK (carbs >= 0),
  fat double precision NOT NULL DEFAULT 0 CHECK (fat >= 0),
  is_liquid boolean NOT NULL DEFAULT false,
  is_recipe boolean NOT NULL DEFAULT false,
  servings double precision NOT NULL DEFAULT 1 CHECK (servings > 0),
  is_favorite boolean NOT NULL DEFAULT false,
  is_deleted boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS public.macro_favorites (
  user_id uuid NOT NULL REFERENCES public.macro_users(id) ON DELETE CASCADE,
  food_name text NOT NULL,
  is_favorite boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, food_name)
);

CREATE TABLE IF NOT EXISTS public.macro_meal_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.macro_users(id) ON DELETE CASCADE,
  food_name text NOT NULL,
  grams double precision NOT NULL CHECK (grams > 0),
  date text NOT NULL CHECK (date = 'default' OR date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  calories double precision NOT NULL DEFAULT 0 CHECK (calories >= 0),
  protein double precision NOT NULL DEFAULT 0 CHECK (protein >= 0),
  carbs double precision NOT NULL DEFAULT 0 CHECK (carbs >= 0),
  fat double precision NOT NULL DEFAULT 0 CHECK (fat >= 0),
  is_liquid boolean NOT NULL DEFAULT false,
  is_recipe boolean NOT NULL DEFAULT false,
  servings double precision NOT NULL DEFAULT 1 CHECK (servings > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.macro_daily_targets (
  user_id uuid NOT NULL REFERENCES public.macro_users(id) ON DELETE CASCADE,
  date text NOT NULL CHECK (date = 'default' OR date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  calories double precision NOT NULL CHECK (calories >= 0),
  protein double precision NOT NULL CHECK (protein >= 0),
  carbs double precision NOT NULL CHECK (carbs >= 0),
  fat double precision NOT NULL CHECK (fat >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, date)
);

CREATE TABLE IF NOT EXISTS public.macro_app_settings (
  user_id uuid PRIMARY KEY REFERENCES public.macro_users(id) ON DELETE CASCADE,
  cal_mode text NOT NULL DEFAULT 'down' CHECK (cal_mode IN ('free', 'up', 'down', 'both')),
  cal_pct double precision NOT NULL DEFAULT 10 CHECK (cal_pct >= 0),
  pro_mode text NOT NULL DEFAULT 'up' CHECK (pro_mode IN ('free', 'up', 'down', 'both')),
  pro_pct double precision NOT NULL DEFAULT 10 CHECK (pro_pct >= 0),
  carb_mode text NOT NULL DEFAULT 'both' CHECK (carb_mode IN ('free', 'up', 'down', 'both')),
  carb_pct double precision NOT NULL DEFAULT 10 CHECK (carb_pct >= 0),
  fat_mode text NOT NULL DEFAULT 'free' CHECK (fat_mode IN ('free', 'up', 'down', 'both')),
  fat_pct double precision NOT NULL DEFAULT 0 CHECK (fat_pct >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.macro_sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.macro_users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.macro_login_attempts (
  username text NOT NULL,
  client_key text NOT NULL,
  window_started_at timestamptz NOT NULL DEFAULT now(),
  failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
  locked_until timestamptz,
  PRIMARY KEY (username, client_key)
);

CREATE INDEX IF NOT EXISTS macro_meal_entries_user_date_idx ON public.macro_meal_entries(user_id, date, id);
CREATE INDEX IF NOT EXISTS macro_user_foods_user_name_idx ON public.macro_user_foods(user_id, name);
CREATE INDEX IF NOT EXISTS macro_sessions_expiry_idx ON public.macro_sessions(expires_at);

