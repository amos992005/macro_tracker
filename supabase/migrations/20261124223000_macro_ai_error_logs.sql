CREATE TABLE IF NOT EXISTS public.macro_ai_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL,
  user_id uuid REFERENCES public.macro_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  mode text NOT NULL CHECK (mode IN ('meal', 'nutrition_label')),
  model text NOT NULL,
  http_status integer,
  error_type text NOT NULL,
  error_message text NOT NULL,
  error_detail text
);

CREATE INDEX IF NOT EXISTS macro_ai_logs_created_at_idx
  ON public.macro_ai_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS macro_ai_logs_request_id_idx
  ON public.macro_ai_logs (request_id);

ALTER TABLE public.macro_ai_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.macro_ai_logs FROM anon, authenticated;
GRANT ALL ON public.macro_ai_logs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.macro_ai_logs_id_seq TO service_role;
